with gr.Blocks(title="IPA Simplificado") as demo:
    gr.Markdown("## IPA Simplificado — Priorización de Requisitos")
    gr.Markdown(
        "Ajusta el número de requisitos, edita la matriz de importancia "
        "(escala sugerida 1-9) y la fila de pesos, y calcula el ranking en vivo."
    )

    with gr.Row():
        num_fr = gr.Slider(1, 8, value=4, step=1, label="N° de requisitos funcionales (FR)")
        num_nfr = gr.Slider(1, 6, value=3, step=1, label="N° de requisitos no funcionales (NFR)")

    with gr.Row():
        nombres_fr = gr.Textbox(
            value="Login,Reportes,Pagos,Notificaciones",
            label="Nombres de los FR (separados por coma)",
        )
        nombres_nfr = gr.Textbox(
            value="Seguridad,Usabilidad,Rendimiento",
            label="Nombres de los NFR (separados por coma)",
        )

    btn_generar = gr.Button("Generar tabla")

    tabla = gr.Dataframe(
        value=generar_tabla(4, 3, "Login,Reportes,Pagos,Notificaciones", "Seguridad,Usabilidad,Rendimiento"),
        interactive=True,
        label="Matriz de decisión D (última fila = pesos W de cada NFR)",
    )

    btn_calcular = gr.Button("Calcular prioridades", variant="primary")

    resumen = gr.Markdown()
    grafico = gr.Plot(label="Ranking")
    tabla_final = gr.Dataframe(label="Detalle del ranking", interactive=False)

    btn_generar.click(
        fn=generar_tabla,
        inputs=[num_fr, num_nfr, nombres_fr, nombres_nfr],
        outputs=tabla,
    )
    btn_calcular.click(fn=calcular, inputs=tabla, outputs=[grafico, resumen, tabla_final])


